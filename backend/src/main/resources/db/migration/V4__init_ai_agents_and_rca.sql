-- AI Agent Runs (Tracking each LangGraph multi-agent run for an incident)
CREATE TABLE IF NOT EXISTS ai_agent_runs (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    incident_id UUID NOT NULL REFERENCES incidents(id) ON DELETE CASCADE,
    triggered_by VARCHAR(50) NOT NULL DEFAULT 'SYSTEM', -- SYSTEM, USER
    model_provider VARCHAR(50) NOT NULL DEFAULT 'GEMINI', -- GEMINI, OPENAI, OLLAMA
    model_name VARCHAR(100) NOT NULL DEFAULT 'gemini-2.5-flash',
    status VARCHAR(50) NOT NULL DEFAULT 'IN_PROGRESS', -- IN_PROGRESS, COMPLETED, FAILED
    total_tokens_used INT DEFAULT 0,
    duration_ms INT DEFAULT 0,
    error_message TEXT,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_ai_runs_incident ON ai_agent_runs(incident_id);

-- AI Agent Steps (Detailed audit of each of the 8 specialized agents)
CREATE TABLE IF NOT EXISTS ai_agent_steps (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    agent_run_id UUID NOT NULL REFERENCES ai_agent_runs(id) ON DELETE CASCADE,
    agent_name VARCHAR(100) NOT NULL, -- InvestigationAgent, LogAgent, MetricsAgent, TracingAgent, DeploymentAgent, RcaAgent, RemediationAgent, ReportingAgent
    step_order INT NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'COMPLETED', -- RUNNING, COMPLETED, FAILED, SKIPPED
    input_summary TEXT,
    output_summary TEXT,
    findings JSONB DEFAULT '{}',
    duration_ms INT DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_ai_steps_run ON ai_agent_steps(agent_run_id);

-- Root Cause Analyses (Final validated RCA synthesized by Agent 6 & Agent 8)
CREATE TABLE IF NOT EXISTS root_cause_analyses (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    incident_id UUID NOT NULL REFERENCES incidents(id) ON DELETE CASCADE,
    agent_run_id UUID REFERENCES ai_agent_runs(id) ON DELETE SET NULL,
    title VARCHAR(255) NOT NULL,
    executive_summary TEXT NOT NULL,
    technical_summary TEXT NOT NULL,
    root_cause_category VARCHAR(100) NOT NULL, -- CODE_DEFECT, INFRA_EXHAUSTION, CONFIG_DRIFT, DEPENDENCY_FAILURE, PIPELINE_ERROR
    confidence_score DOUBLE PRECISION NOT NULL, -- e.g. 0.94
    facts JSONB DEFAULT '[]',
    hypotheses JSONB DEFAULT '[]',
    timeline_summary JSONB DEFAULT '[]',
    lessons_learned TEXT,
    preventative_measures JSONB DEFAULT '[]',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_rca_incident ON root_cause_analyses(incident_id);

-- AI Recommendations (Generated by Remediation Planning Agent 7)
CREATE TABLE IF NOT EXISTS ai_recommendations (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    incident_id UUID NOT NULL REFERENCES incidents(id) ON DELETE CASCADE,
    agent_run_id UUID REFERENCES ai_agent_runs(id) ON DELETE SET NULL,
    action_type VARCHAR(100) NOT NULL, -- RESTART_POD, SCALE_DEPLOYMENT, ROLLBACK_DEPLOYMENT, RESTART_SERVICE, CLEAR_CACHE, FLUSH_CONNECTIONS
    target_resource VARCHAR(255) NOT NULL, -- e.g. payment-service-deployment
    parameters JSONB DEFAULT '{}',
    risk_level VARCHAR(30) NOT NULL DEFAULT 'MEDIUM', -- LOW, MEDIUM, HIGH, CRITICAL
    requires_approval BOOLEAN NOT NULL DEFAULT true,
    status VARCHAR(50) NOT NULL DEFAULT 'PENDING_APPROVAL', -- PENDING_APPROVAL, APPROVED, REJECTED, EXECUTED, FAILED
    justification TEXT NOT NULL,
    remediation_action_id UUID, -- points to remediation_actions once created
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_ai_recommendations_incident ON ai_recommendations(incident_id);
